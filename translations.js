// Language Manager
class LanguageManager {
    constructor() {
        this.currentLang = localStorage.getItem('prunavita_lang') || 'es';
        this.init();
    }

    init() {
        // Set initial language
        this.setLanguage(this.currentLang, false);

        // Setup language switcher buttons
        const langButtons = document.querySelectorAll('.lang-btn');
        langButtons.forEach(btn => {
            btn.addEventListener('click', () => {
                const lang = btn.getAttribute('data-lang');
                this.setLanguage(lang);
            });
        });
    }

    setLanguage(lang, save = true) {
        this.currentLang = lang;

        // Update HTML lang attribute
        document.documentElement.setAttribute('lang', lang);
        document.documentElement.setAttribute('data-lang', lang);

        // Update all translatable elements
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = translations[lang][key];

            if (translation) {
                // Handle different element types
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = translation;
                } else if (el.tagName === 'OPTION') {
                    el.textContent = translation;
                } else {
                    el.innerHTML = translation;
                }
            }
        });

        // Update active button
        document.querySelectorAll('.lang-btn').forEach(btn => {
            if (btn.getAttribute('data-lang') === lang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });

        // Save preference
        if (save) {
            localStorage.setItem('prunavita_lang', lang);
        }

        // Update page title
        document.title = lang === 'es'
            ? 'Prunavita | Exportación de Fruta Deshidratada Premium'
            : 'Prunavita | Premium Dried Fruit Export';
    }

    getCurrentLang() {
        return this.currentLang;
    }

    translate(key) {
        return translations[this.currentLang][key] || key;
    }
}

// Initialize language manager when DOM is ready
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { translations, LanguageManager };
}
